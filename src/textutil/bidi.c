/* Which way a line of text is read, which the HTML writer needs to know to say
 * whether the paragraph it is writing needs dir="rtl".
 *
 * The question is the first one the Unicode bidirectional algorithm asks of a
 * paragraph, and the reference tool answers it the same way: read the line from
 * its start and stop at the first character that has a direction of its own.  A
 * letter written left to right there settles the line whatever follows it, so
 * an English letter ahead of an Arabic one does not make the line read right to
 * left, and a line of nothing but marks and punctuation settles nothing and is
 * read left to right.  A left to right and a right to left mark are themselves
 * letters in this sense, so a mark at the head of a line is what settles it,
 * which is why the writer has to ask about marks as well as about the text
 * beside them.
 *
 * So this is a table of the two strong directions and nothing else.  Both are
 * the sets the reference tool uses, which are not quite those of the Unicode
 * data files: the reference counts a code point that Unicode leaves unassigned
 * as left to right, so the left to right ranges run across whole blocks that
 * are mostly holes, and U+0590 and U+05C8 through U+05FF are right to left
 * where Unicode 16 calls them unassigned.  The ranges were read off the
 * reference tool rather than from the data files, one code point at a time, so
 * they agree with it here whatever a later Unicode version says.
 */

