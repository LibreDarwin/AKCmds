static int range_has(unsigned long cp, int rtl)
{
	size_t lo = 0, hi = sizeof(strong) / sizeof(strong[0]);

	while (lo < hi) {
		size_t mid = lo + (hi - lo) / 2;

		if (cp < strong[mid].lo)
			hi = mid;
		else if (cp > strong[mid].hi)
			lo = mid + 1;
		else
			return strong[mid].rtl == rtl;
	}
	return 0;
}

/* The direction of the first code point in a line that has one, or 0 for a
 * line that has none.  The return is the direction rather than a name so that
 * a line with nothing strong in it reads the same as a line whose first strong
 * character is left to right, which is how both are written out. */
unsigned long tu_bidi_first(const unsigned char *p, size_t n)
{
	size_t i = 0;

	while (i < n) {
		unsigned long cp;
		size_t width;

		cp = tu_utf8_strict(p + i, n - i, &width);
		if (range_has(cp, 1))
			return 1;
		if (range_has(cp, 0))
			return 0;
		i += width;
	}
	return 0;
}

/* The mark a line opens with, when it opens with one: U+200E, U+200F, or 0
 * when it does not.  Which of the two it is matters as much as whether there
 * is one -- the right-to-left mark names a direction, the left-to-right one
 * only says that a direction was named -- so the writers that record the
 * difference ask for the mark rather than for its length. */
unsigned long tu_bidi_open(const unsigned char *p, size_t n)
{
	if (n >= 3 && p[0] == 0xE2 && p[1] == 0x80 && p[2] == 0x8E)
		return 0x200E;
	if (n >= 3 && p[0] == 0xE2 && p[1] == 0x80 && p[2] == 0x8F)
		return 0x200F;
	return 0;
}

/* The number of bytes at the head of a line that are a mark telling a reader
 * which way to read rather than text, and so are left out of a line that
 * begins with one.  A left or right to left mark is one of these wherever it
 * leads a line, and the reference tool drops the first of them whatever
 * follows, keeping a second: a line of two right to left marks keeps the one
 * the first was hiding.  A mark anywhere else in a line is left alone, and so
 * is a byte order mark, which the reader of the text has already taken off the
 * front of the text as a whole rather than off each of its lines. */
size_t tu_bidi_mark(const unsigned char *p, size_t n)
{
	return tu_bidi_open(p, n) ? 3 : 0;
}
